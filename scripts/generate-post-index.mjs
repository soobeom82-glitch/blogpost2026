import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { primaryCategoryMeta, topicMeta, seriesTypeMeta } from "../lib/post-taxonomy.js";

const root = process.cwd();
const dir = path.join(root, "content/posts");
const files = (await fs.readdir(dir)).filter((file) => file.endsWith(".mdx")).sort();
const seriesOrders = new Set();
const imports = [];
const entries = [];
for (const [index, file] of files.entries()) {
  const source = await fs.readFile(path.join(dir, file), "utf8");
  const match = source.match(/^export const metadata = (\{[\s\S]*?\n\});/);
  if (!match) throw new Error(`${file}: metadata export is missing`);
  const metadata = vm.runInNewContext(`(${match[1]})`, Object.create(null), { timeout: 1000 });
  for (const key of ["title", "summary", "publishedAt", "category", "primaryCategory"])
    if (typeof metadata[key] !== "string" || !metadata[key].trim())
      throw new Error(`${file}: ${key} is required`);
  if (
    !/^\d{4}-\d{2}-\d{2}$/.test(metadata.publishedAt) ||
    new Date(metadata.publishedAt).toISOString().slice(0, 10) !== metadata.publishedAt
  )
    throw new Error(`${file}: invalid publishedAt`);
  if (!primaryCategoryMeta[metadata.primaryCategory]) throw new Error(`${file}: unknown category`);
  const section = metadata.section || "business";
  if (!["business", "personal"].includes(section)) throw new Error(`${file}: unknown section`);
  if ((metadata.primaryCategory === "travel") !== (section === "personal"))
    throw new Error(`${file}: travel category belongs in the personal section`);
  if (
    !Array.isArray(metadata.topics) ||
    !metadata.topics.length ||
    metadata.topics.some((topic) => !topicMeta[topic])
  )
    throw new Error(`${file}: invalid topics`);
  if (metadata.series) {
    const key = `${metadata.series}:${metadata.seriesOrder}`;
    if (
      !Number.isInteger(metadata.seriesOrder) ||
      metadata.seriesOrder < 1 ||
      seriesOrders.has(key) ||
      !seriesTypeMeta[metadata.seriesType]
    )
      throw new Error(`${file}: invalid or duplicate series order/type`);
    seriesOrders.add(key);
  }
  for (const image of source.matchAll(/\/images\/[^\s"'<>`)]+/g))
    await fs.access(path.join(root, "public", image[0]));
  for (const link of source.matchAll(/\/blog\/([a-z0-9-]+)/g))
    if (!files.includes(`${link[1]}.mdx`))
      throw new Error(`${file}: missing linked post ${link[1]}`);
  imports.push(`import Post${index}, { metadata as metadata${index} } from "./${file}";`);
  entries.push(`  { slug: "${file.slice(0, -4)}", ...metadata${index}, Content: Post${index} }`);
}
const output = `// Generated by npm run content:generate. Edit MDX metadata instead.\n${imports.join("\n")}\n\nexport const allPosts = [\n${entries.join(",\n")}\n];\n`;
const target = path.join(dir, "index.js");
if (process.argv.includes("--check")) {
  if ((await fs.readFile(target, "utf8")) !== output)
    throw new Error("Post index is stale. Run npm run content:generate.");
} else await fs.writeFile(target, output);
console.log(`Validated ${files.length} posts, series order, image paths, and article links.`);
